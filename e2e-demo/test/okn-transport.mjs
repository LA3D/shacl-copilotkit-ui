import assert from 'node:assert/strict';
import { HttpAgent } from '@ag-ui/client';
import { EventSchemas } from '@ag-ui/core/schemas';
import { ViewSchema } from '../server/okn.mjs';
const base = 'http://127.0.0.1:4173';
const agent = new HttpAgent({ url: base + '/api/okn/agent', initialState: {} });
const events = [];
agent.subscribe({ onStateSnapshotEvent: ({ event }) => { EventSchemas.parse(event); events.push(event.type); } });
await agent.runAgent({ forwardedProps: { question: 'compare', source: 'snapshot' } });
assert.equal(agent.state.view.kind, 'comparison'); assert.equal(agent.state.rows.length, 3);
const datasetId = agent.state.view.datasetId;
await agent.runAgent({ forwardedProps: { question: 'evidence', source: 'snapshot' } });
assert.equal(agent.state.view.kind, 'table'); assert.equal(agent.state.view.datasetId, datasetId);
const call = agent.messages.filter(m => m.role === 'assistant').flatMap(m => m.toolCalls ?? []).at(-1);
assert.equal(call.function.name, 'show_okn'); ViewSchema.parse(JSON.parse(call.function.arguments));
await agent.runAgent({ forwardedProps: { question: 'compare', source: 'snapshot' } });
assert.equal(agent.state.view.kind, 'comparison'); assert.equal(events.length, 3);
const denied = await fetch(base + '/api/okn/agent', { method: 'POST', headers: { 'content-type': 'application/json', origin: 'https://example.invalid' }, body: '{}' });
assert.equal(denied.status, 403);
console.log('OKN transport: snapshot, question switch, validated tool spec, repeat and cross-origin rejection passed');
